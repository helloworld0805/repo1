-- MySQL 8 DDL for workflow record table
CREATE TABLE IF NOT EXISTS `workflow_record` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  `module_id` VARCHAR(64) NOT NULL COMMENT '流程模型id',
  `version` VARCHAR(32) NULL DEFAULT NULL COMMENT '版本号',
  `bytes` LONGBLOB NULL COMMENT '模型图字节码（与img_url二选一，建议使用img_url）',
  `img_url` VARCHAR(512) NULL DEFAULT NULL COMMENT '模型图片地址（与bytes二选一，建议此项）',
  `process_id` VARCHAR(64) NOT NULL COMMENT '流程实例id',
  `process_name` VARCHAR(128) NOT NULL COMMENT '流程名称',
  `current_node_id` VARCHAR(64) NOT NULL COMMENT '当前节点id',
  `current_node_name` VARCHAR(128) NOT NULL COMMENT '当前节点名称',
  `create_time` DATETIME NOT NULL COMMENT '创建时间',
  `end_time` DATETIME NULL DEFAULT NULL COMMENT '结束时间',
  `initiator_id` VARCHAR(32) NOT NULL COMMENT '流程发起人身份证号码/唯一标识',
  `initiator_name` VARCHAR(64) NOT NULL COMMENT '流程发起人姓名',
  `dept_id` VARCHAR(64) NOT NULL COMMENT '部门编码',
  `major_category_id` VARCHAR(64) NOT NULL COMMENT '流程大类id',
  `major_category_name` VARCHAR(128) NOT NULL COMMENT '流程大类名称',
  `category_id` VARCHAR(64) NOT NULL COMMENT '流程小类id',
  `category_name` VARCHAR(128) NOT NULL COMMENT '流程小类名称',
  `source` TINYINT NOT NULL COMMENT '来源：1-基控，2-监督，3-案件',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '记录创建时间',
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '记录更新时间',
  PRIMARY KEY (`id`),
  INDEX `idx_process_id` (`process_id`),
  INDEX `idx_module_id` (`module_id`),
  INDEX `idx_create_time` (`create_time`),
  INDEX `idx_dept_id` (`dept_id`),
  CONSTRAINT `chk_source` CHECK (`source` IN (1,2,3))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='流程运行记录';